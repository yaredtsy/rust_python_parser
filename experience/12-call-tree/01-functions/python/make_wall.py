"""Writes wall_big.py: WIDTH functions per level, DEPTH levels, each calling
every function of the next level. Not a fixture. Run it, then time the
`calls` binary on the result.

    python3 make_wall.py 4 8      # 4 wide, 8 deep: 87,381 walks inline
"""

import sys

width = int(sys.argv[1]) if len(sys.argv) > 1 else 4
depth = int(sys.argv[2]) if len(sys.argv) > 2 else 8

lines = ['"""Generated by make_wall.py. Do not edit."""', ""]
for level in range(depth, 0, -1):
    for i in range(width):
        lines.append(f"def f{level}_{i}():")
        if level == depth:
            lines.append("    pass")
        else:
            for j in range(width):
                lines.append(f"    f{level + 1}_{j}()")
        lines.append("")
lines.append("def main():")
for j in range(width):
    lines.append(f"    f1_{j}()")
lines.append("")

walks = sum(width**k for k in range(depth + 1))
functions = 1 + width * depth
with open("wall_big.py", "w") as out:
    out.write("\n".join(lines))
print(f"wall_big.py: {functions} functions, {walks:,} walks in inline mode")
